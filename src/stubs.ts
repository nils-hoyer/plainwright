import fs from 'node:fs';
import path from 'node:path';
import { customParameterTypes } from './params';
import { getSteps } from './registry';

/** Where `init` and the `stubs` script write the step list for the editor. */
export const STUBS_FILE = '.vscode/plainwright.steps.js';

/**
 * A JavaScript file the Cucumber editor extensions can read to offer autocomplete and
 * go-to-definition for all steps, including keywords from .feature files.
 *
 * The extensions only recognize literal `Given('pattern', ...)` calls and
 * `defineParameterType({ name, regexp })`. This file has exactly that shape.
 * It is never executed; do not include it in playwright-bdd's `steps`.
 */
export function renderStubs(): string {
  const lines = [
    '// Generated by `plainwright stubs` for editor support. Do not edit or run this file.',
    '// VS Code (Cucumber extension): add this file to "cucumber.glue" in .vscode/settings.json.',
    '/* eslint-disable */',
    '',
    ...customParameterTypes.map(
      ({ name, regexps }) =>
        `defineParameterType({ name: ${JSON.stringify(name)}, regexp: ${
          regexps.length === 1 ? regexps[0] : `[${regexps.join(', ')}]`
        } });`,
    ),
    '',
  ];
  for (const step of getSteps()) {
    lines.push(`// ${step.description}`);
    lines.push(`Given(${JSON.stringify(step.pattern)}, () => {});`);
  }
  return `${lines.join('\n')}\n`;
}

/**
 * Rewrites the editor's step list when keywords or steps changed, so new keywords show up in the
 * editor after the next `plainwright test` or `plainwright lint`. It writes the file when it
 * exists or when the VS Code settings name it outside a comment: the file is not committed, so it
 * is missing after a clone. The list is only for the editor, so a file that cannot be written
 * never stops a test run or lint.
 */
export function refreshStubs(cwd: string) {
  const file = path.join(cwd, STUBS_FILE);
  try {
    const exists = fs.existsSync(file);
    if (!exists && !namedInSettings(cwd)) return;
    const stubs = renderStubs();
    if (exists && fs.readFileSync(file, 'utf8') === stubs) return;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, stubs);
  } catch {
    // The editor then keeps the list it has.
  }
}

/** Whether .vscode/settings.json names the step list on a line that is not a // comment. */
function namedInSettings(cwd: string) {
  const settings = path.join(cwd, '.vscode/settings.json');
  if (!fs.existsSync(settings)) return false;
  return fs
    .readFileSync(settings, 'utf8')
    .split('\n')
    .some((line) => line.includes(STUBS_FILE) && !line.trimStart().startsWith('//'));
}
